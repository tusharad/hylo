-- | Test Table A: user entity with primary key, nullable note, optimistic lock version.
data UserT (ctx :: Ctx) = User
  { id :: !(Col ctx (Id UserT Int64))
  , email :: !(Col ctx Text)
  , note :: !(Col ctx (Maybe Text))
  , version :: !(Col ctx Int64)
  }

-- | Test Table B: organization entity without description.
data OrgT (ctx :: Ctx) = Org
  { id :: !(Col ctx (Id OrgT Int64))
  , name :: !(Col ctx Text)
  }

-- | Test Table C: document entity with a Redis cache policy.
data DocT (ctx :: Ctx) = Doc
  { id :: !(Col ctx (Id DocT Int64))
  , title :: !(Col ctx Text)
  }

-- | Wide table repeated ten times to exercise the token budget SLOs.
data WideT (ctx :: Ctx) = Wide
  { wId :: !(Col ctx (Id WideT Int64))
  , wA :: !(Col ctx Text)
  , wB :: !(Col ctx Text)
  , wC :: !(Col ctx Text)
  , wD :: !(Col ctx (Maybe Text))
  , wE :: !(Col ctx Bool)
  , wV :: !(Col ctx Int64)
  }

userMeta :: UserT 'Meta
userMeta =
  User
    { id = primaryKey "id" "bigint"
    , email = column "email" "text"
    , note = nullableColumn "note" "text"
    , version = optimisticLockColumn "version" "bigint"
    }

userSchema :: TableSchema UserT
userSchema = withTableDescription "User accounts" (tableSchema "users" userMeta)

orgMeta :: OrgT 'Meta
orgMeta =
  Org
    { id = primaryKey "id" "bigint"
    , name = column "name" "text"
    }

orgSchema :: TableSchema OrgT
orgSchema = tableSchema "orgs" orgMeta

docMeta :: DocT 'Meta
docMeta =
  Doc
    { id = primaryKey "id" "bigint"
    , title = column "title" "text"
    }

describedDocSchema :: TableSchema DocT
describedDocSchema = withTableDescription "Uploaded documents" (tableSchema "documents" docMeta)

docSchema :: TableSchema DocT
docSchema = withRedisCache (RedisCachePolicy "docs:" 120) describedDocSchema

wideMeta :: WideT 'Meta
wideMeta =
  Wide
    { wId = primaryKey "id" "bigint"
    , wA = column "col_a" "text"
    , wB = column "col_b" "text"
    , wC = column "col_c" "text"
    , wD = nullableColumn "col_d" "text"
    , wE = column "col_e" "boolean"
    , wV = optimisticLockColumn "col_v" "bigint"
    }

wideSchema :: Text -> TableSchema WideT
wideSchema name = tableSchema name wideMeta

instance Table UserT where
  toTableExpr alias m =
    User
      { id = colSpecExpr alias m.id
      , email = colSpecExpr alias m.email
      , note = colSpecExpr alias m.note
      , version = colSpecExpr alias m.version

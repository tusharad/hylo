spec :: Spec
spec = describe "US18: Hylo.AI.Context.Exporter (AGENTS.md & llms.txt)" $ do
  describe "1. Deterministic AGENTS.md rendering" $ do
    it "renders byte-exact AGENTS.md for a fixed schema snapshot" $ do
      exportAgentsMarkdown singleUserRegistry defaultAiContextConfig `shouldBe` goldenAgents

    it "renders byte-identical AGENTS.md across repeated invocations for arbitrary budgets" $
      property $ \(Positive b) ->
        let cfg = defaultAiContextConfig {acTokenBudget = b}
         in exportAgentsMarkdown fixtureRegistry cfg == exportAgentsMarkdown fixtureRegistry cfg

  describe "2. Deterministic llms.txt rendering" $ do
    it "renders byte-exact llms.txt for a fixed schema snapshot" $ do
      exportLlmsTxt singleUserRegistry defaultAiContextConfig `shouldBe` goldenLlms

    it "follows the llms.txt format: # Title, > description, ## Schema" $ do
      let rendered = T.unpack (exportLlmsTxt fixtureRegistry defaultAiContextConfig)
      take 1 (lines rendered) `shouldBe` ["# Hylo Database Schema"]
      rendered `shouldContain` "> Schema context for 3 table(s)"
      rendered `shouldContain` "## Schema"

  describe "3. Registry filtering" $ do
    it "restricts output to acIncludeTables when the list is non-empty" $ do
      let cfg = defaultAiContextConfig {acIncludeTables = ["users"]}
          rendered = T.unpack (exportAgentsMarkdown fixtureRegistry cfg)
      rendered `shouldContain` "| users | id |"
      rendered `shouldNotContain` "## Table: orgs"
      rendered `shouldNotContain` "## Table: documents"

    it "includes every table when acIncludeTables is empty" $ do
      let rendered = T.unpack (exportAgentsMarkdown fixtureRegistry defaultAiContextConfig)
      rendered `shouldContain` "## Table: users"
      rendered `shouldContain` "## Table: orgs"
      rendered `shouldContain` "## Table: documents"

    it "omits acExcludeColumns from per-table column sections" $ do
      let cfg = defaultAiContextConfig {acExcludeColumns = ["email"]}
          rendered = T.unpack (exportAgentsMarkdown singleUserRegistry cfg)
      rendered `shouldNotContain` "| email |"
      rendered `shouldContain` "| id |"

  describe "4. Schema metadata annotations" $ do
    it "renders the redis cache policy as a table annotation" $ do
      T.unpack (exportAgentsMarkdown fixtureRegistry defaultAiContextConfig)
        `shouldContain` "Cache: Redis (key prefix \"docs:\", ttl 120s)"

    it "renders an em dash description for tables without tableDescription" $ do
      T.unpack (exportAgentsMarkdown fixtureRegistry defaultAiContextConfig)
        `shouldContain` "| orgs | id | — | — |"

  describe "5. Query Patterns section" $ do
    it "lists AgentPolicy exposed columns with an example JSON tool-call payload" $ do
      let cfg =
            defaultAiContextConfig
              { acQueryPolicies = [QueryPattern "users" ["email", "org_id"] 50]
              }
          rendered = T.unpack (exportAgentsMarkdown singleUserRegistry cfg)
      rendered `shouldContain` "### query_users"
      rendered `shouldContain` "Allowed filter columns: email, org_id"
      rendered
        `shouldContain` "{\"tool\": \"query_users\", \"args\": {\"filter\": {\"email\": {\"$eq\": \"...\"}}}, \"limit\": 50}"

    it "falls back to a defaultPolicy note when no policies are configured" $ do
      T.unpack (exportAgentsMarkdown singleUserRegistry defaultAiContextConfig)
        `shouldContain` "No `AgentPolicy` column whitelists are configured"

  describe "6. Token budget laws" $ do
    it "keeps AGENTS.md within the token budget for arbitrary positive budgets" $
      property $ \(Positive b) ->
        estimateTokens (exportAgentsMarkdown wideRegistry (defaultAiContextConfig {acTokenBudget = b})) <= b

    it "keeps llms.txt within the token budget for arbitrary positive budgets" $
      property $ \(Positive b) ->
        estimateTokens (exportLlmsTxt wideRegistry (defaultAiContextConfig {acTokenBudget = b})) <= b

    it "keeps llms.txt under 2K tokens for a 10-table schema at the default budget" $ do
      estimateTokens (exportLlmsTxt wideRegistry defaultAiContextConfig) `shouldSatisfy` (< 2048)

    it "keeps AGENTS.md within 4096 tokens for a 10-table schema at the default budget" $ do
      estimateTokens (exportAgentsMarkdown wideRegistry defaultAiContextConfig) `shouldSatisfy` (<= 4096)

  describe "7. fitTokenBudget algebraic laws" $ do
    it "never exceeds the budget" $
      property $ \(Positive b) (s :: String) ->
        estimateTokens (fitTokenBudget b (T.pack s)) <= b

    it "is a no-op when the input already fits" $
      property $ \(Positive b) (s :: String) ->
        let t = T.pack s
         in estimateTokens t <= b ==> fitTokenBudget b t == t

    it "is idempotent" $
      property $ \(Positive b) (s :: String) ->
        fitTokenBudget b (fitTokenBudget b (T.pack s)) == fitTokenBudget b (T.pack s)

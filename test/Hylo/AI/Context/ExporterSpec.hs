instance Table DocT where
  toTableExpr alias m =
    Doc
      { id = colSpecExpr alias m.id
      , title = colSpecExpr alias m.title
      }
  tableColDefs m =
    [ eraseColDef m.id
    , eraseColDef m.title
    ]

instance Table WideT where
  toTableExpr alias m =
    Wide
      { wId = colSpecExpr alias m.wId
      , wA = colSpecExpr alias m.wA
      , wB = colSpecExpr alias m.wB
      , wC = colSpecExpr alias m.wC
      , wD = colSpecExpr alias m.wD
      , wE = colSpecExpr alias m.wE
      , wV = colSpecExpr alias m.wV
      }
  tableColDefs m =
    [ eraseColDef m.wId
    , eraseColDef m.wA
    , eraseColDef m.wB
    , eraseColDef m.wC
    , eraseColDef m.wD
    , eraseColDef m.wE
    , eraseColDef m.wV
    ]

singleUserRegistry :: [AnyTableSchema]
singleUserRegistry = [AnyTableSchema userSchema]

fixtureRegistry :: [AnyTableSchema]
fixtureRegistry =
  [ AnyTableSchema userSchema
  , AnyTableSchema orgSchema
  , AnyTableSchema docSchema
  ]

wideRegistry :: [AnyTableSchema]
wideRegistry = [AnyTableSchema (wideSchema ("wide_" <> T.pack (show i))) | i <- [1 :: Int .. 10]]

